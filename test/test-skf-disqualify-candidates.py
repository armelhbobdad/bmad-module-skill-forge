class TestAutoGeneratedMarker:
    def test_at_generated_line_1(self, tmp_path: Path) -> None:
        f = _write(tmp_path / "f.py", "# @generated\nprint('hi')\n")
        assert mod.has_auto_generated_marker(f) == "@generated"

    def test_generated_code_comment(self, tmp_path: Path) -> None:
        f = _write(tmp_path / "f.ts", "// GENERATED CODE: DO NOT EDIT\nexport {}\n")
        assert mod.has_auto_generated_marker(f) == "// generated code"

    def test_autogenerated_python_comment(self, tmp_path: Path) -> None:
        f = _write(tmp_path / "f.py", "# AUTOGENERATED FILE\nx = 1\n")
        assert mod.has_auto_generated_marker(f) == "# autogenerated"

    def test_html_comment(self, tmp_path: Path) -> None:
        f = _write(tmp_path / "f.html", "<!-- generated -->\n<html></html>\n")
        assert mod.has_auto_generated_marker(f) == "<!-- generated -->"

    def test_case_insensitive(self, tmp_path: Path) -> None:
        f = _write(tmp_path / "f.py", "# @Generated by tool\nx = 1\n")
        assert mod.has_auto_generated_marker(f) == "@generated"

    def test_within_first_10_lines(self, tmp_path: Path) -> None:
        # marker at line 10: still within the scan window
        body = "\n".join([f"# line {i}" for i in range(1, 10)] + ["@generated"]) + "\n"
        f = _write(tmp_path / "f.py", body)
        assert mod.has_auto_generated_marker(f) == "@generated"

    def test_beyond_first_10_lines_misses(self, tmp_path: Path) -> None:
        # marker at line 12: outside the scan window
        body = "\n".join(
            [f"# line {i}" for i in range(1, 12)] + ["// GENERATED CODE"]
        ) + "\n"
        f = _write(tmp_path / "f.py", body)
        assert mod.has_auto_generated_marker(f) is None

    def test_no_marker(self, tmp_path: Path) -> None:
        f = _write(tmp_path / "f.py", "def foo():\n    return 1\n")
        assert mod.has_auto_generated_marker(f) is None

    def test_unreadable_file_returns_none(self, tmp_path: Path) -> None:
        # nonexistent file: silently None (the header scan is opportunistic)
        assert mod.has_auto_generated_marker(tmp_path / "missing.py") is None


