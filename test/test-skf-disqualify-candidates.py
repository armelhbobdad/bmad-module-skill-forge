# --------------------------------------------------------------------------


def _write(path: Path, content: str = "") -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(content.encode("utf-8"))
    return path


def _boundary(name: str, path: str, files: list[str]) -> dict:
    return {"name": name, "path": path, "files": files}


def _make_files(
    source_root: Path, boundary_path: str, file_specs: dict[str, str]
) -> list[str]:
    """Materialize <source_root>/<boundary_path>/<file_rel> for each entry
    in file_specs and return the list of `files[]` paths in source-root-
    relative form (matching how scan-project would record them).
    """
    files: list[str] = []
    for rel, content in file_specs.items():
        full = source_root / boundary_path / rel
        _write(full, content)
        # source-root-relative form, forward-slash for cross-platform JSON
        files.append((Path(boundary_path) / rel).as_posix())
    return files


def _evaluate(
    tmp_path: Path, name: str, path: str, files: list[str], **kwargs
) -> dict:
    return mod.evaluate_boundary(
        _boundary(name, path, files), source_root=tmp_path, **kwargs
    )


