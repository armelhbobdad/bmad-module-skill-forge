class TestCountNonblankLines:
    def test_empty_file(self, tmp_path: Path) -> None:
        f = _write(tmp_path / "f.py", "")
        assert mod.count_nonblank_lines(f) == 0

    def test_only_whitespace(self, tmp_path: Path) -> None:
        f = _write(tmp_path / "f.py", "   \n\t\n  \n")
        assert mod.count_nonblank_lines(f) == 0

    def test_mixed_content_and_blanks(self, tmp_path: Path) -> None:
        f = _write(
            tmp_path / "f.py",
            "import os\n"   # 1
            "\n"            # blank
            "def foo():\n"  # 2
            "   \n"         # whitespace-only: blank
            "    return 1\n"  # 3
        )
        assert mod.count_nonblank_lines(f) == 3

    def test_trailing_newline(self, tmp_path: Path) -> None:
        f = _write(tmp_path / "f.py", "x = 1\ny = 2\n")
        assert mod.count_nonblank_lines(f) == 2

    def test_no_trailing_newline(self, tmp_path: Path) -> None:
        f = _write(tmp_path / "f.py", "x = 1\ny = 2")  # no trailing \n
        assert mod.count_nonblank_lines(f) == 2

    def test_missing_file_returns_zero(self, tmp_path: Path) -> None:
        assert mod.count_nonblank_lines(tmp_path / "missing.py") == 0


