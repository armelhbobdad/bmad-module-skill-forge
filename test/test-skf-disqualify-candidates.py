class TestEvaluateBoundary:
    def test_kept_boundary(self, tmp_path: Path) -> None:
        # 5 files * 30 non-blank lines = 150 LoC: passes both thresholds
        body = "x = 1\n" * 30
        files = _make_files(
            tmp_path,
            "pkg/auth",
            {f"file{i}.py": body for i in range(5)},
        )
        result = _evaluate(tmp_path, "auth", "pkg/auth", files)
        assert result["kind"] == "kept"
        assert result["record"]["name"] == "auth"
        assert result["record"]["path"] == "pkg/auth"
        assert result["record"]["files_count"] == 5
        assert result["record"]["loc_total"] == 150
        assert result["record"]["generated_ratio"] == 0.0
        assert result["record"]["passes_with_generated"] is True
        assert result["record"]["manifest"] is None

    def test_passes_with_generated(self, tmp_path: Path) -> None:
        """A size drop the flagged files caused says whether they would lift it."""
        files = _make_files(tmp_path, "tool", {
            "main.go": BODY_40,
            "build/gen.go": BODY_40,
            "build/types.go": BODY_40,
        })
        record = _evaluate(tmp_path, "tool", "tool", files)["record"]
        assert (record["reason"], record["files_count"]) == ("too-few-files", 1)
        assert record["passes_with_generated"] is True
        small = _make_files(tmp_path, "tiny", {
            "main.go": "package main\n",
            "build/gen.go": "package build\n",
            "build/more.go": "package build\n",
        })
        record = _evaluate(tmp_path, "tiny", "tiny", small)["record"]
        assert (record["reason"], record["passes_with_generated"]) == (
            "too-few-files", False)  # three files, three lines

    def test_dropped_too_few_files(self, tmp_path: Path) -> None:
        body = "x = 1\n" * 60  # plenty of LoC
        files = _make_files(
            tmp_path,
            "pkg/tiny",
            {f"f{i}.py": body for i in range(2)},
        )
        result = _evaluate(tmp_path, "tiny", "pkg/tiny", files)
        assert result["kind"] == "dropped"
        record = result["record"]
        assert record["reason"] == "too-few-files"
        assert record["path"] == "pkg/tiny"
        assert record["files_count"] == 2
        assert record["context"] == {"threshold": 3}

    def test_dropped_too_low_loc(self, tmp_path: Path) -> None:
        # 5 files * 12 lines = 60 LoC: below the 100 threshold
        body = "x = 1\n" * 12
        files = _make_files(
            tmp_path,
            "pkg/skinny",
            {f"f{i}.py": body for i in range(5)},
        )
        result = _evaluate(tmp_path, "skinny", "pkg/skinny", files)
        assert result["kind"] == "dropped"
        record = result["record"]
        assert record["reason"] == "too-low-loc"
        assert record["files_count"] == 5
        assert record["loc_total"] == 60
        assert record["context"] == {"threshold": 100}

    def test_all_vendored_is_generated_code(self, tmp_path: Path) -> None:
        # every source file under node_modules/: the path check is string-only
        files = [
            "vendor-app/node_modules/react/index.js",
            "vendor-app/node_modules/react/lib/foo.js",
            "vendor-app/node_modules/react/package.json",
        ]
        result = _evaluate(tmp_path, "vendor-app", "vendor-app", files)
        assert result["kind"] == "dropped"
        record = result["record"]
        assert record["reason"] == "generated-code"
        assert record["context"] == {
            "first_match": "vendor-app/node_modules/react/index.js",
            "matched_segment": "node_modules/",
        }
