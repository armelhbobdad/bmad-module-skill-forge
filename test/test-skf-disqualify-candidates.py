#!/usr/bin/env python3
"""Tests for skf-disqualify-candidates.py.

Covers:
  - find_generated_segment: node_modules/, vendor/, __pycache__/, .next/,
    .gradle/ at any depth; dist/, build/, target/ only as the first folder
    or beside a manifest (a Java package folder named build/ is source)
  - below_boundary: the segment is looked for below the boundary path
  - is_lockfile / is_non_source: lockfiles, documentation, data, media,
    binaries, manifests and build and tool configuration are never source
    files; unknown extensions are
  - has_auto_generated_marker: @generated / // GENERATED CODE /
    # AUTOGENERATED / <!-- generated --> within first 10 lines
  - count_nonblank_lines: empty file, whitespace-only lines, trailing
    newline, mix of content + blanks
  - evaluate_boundary: a boundary drops as generated only when every source
    file is generated; the reproduced cases (a crate with Cargo.lock, a
    package with src/build/, a Go module with vendor/, a Maven module with
    a com/acme/build/ package) stay; counts leave out lockfiles, non-source
    and generated files; passes_with_generated; rule order; kept records
  - manifest: the own manifest's path, ecosystem, name and private flag
  - signals: each presence flag and its limits
  - filter_boundaries: stats by_reason and mixed, kept/dropped partitions,
    empty input
  - validate_boundaries: missing name/path, wrong types; `files` optional
  - listing: a boundary without `files` gets what git lists under its
    path (ignored build output and dependencies out, each path once), or a
    walk that skips node_modules/ and __pycache__/ outside a work tree or
    in a folder the outer work tree ignores; hidden entries out either way;
    `./packages/auth` and `packages/auth/` list `packages/auth`, and a path
    that leaves the source root exits 1; --tree-dir writes each boundary's
    list (UTF-8, whatever the names) and its record names it in
    `tree_file`, which skf-detect-language.py reads
  - CLI: file input, stdin (-) piping, exit codes for malformed input
  - the manifest names and readers come from skf-scan-manifests.py (hence
    the Python 3.11 floor), and identify-units.md, map-and-detect.md,
    generate-briefs.md and unit-detection-heuristics.md describe the
    helpers as they work
"""

