"""SKF Disqualify Candidates: size, generated-code and signal evidence per boundary.

`identify-units.md` section 2 hands this helper every detected boundary, and
the helper lists each boundary's files itself. What it checks has one right
answer per file list (file and
line counts, generated or vendored directory segments, generated-code header
sentinels, which signal files exist, what the boundary's own manifest names),
and prior runs showed models miscount files, miss generated paths inside
nested `node_modules/` and forget to scan for `@generated`, so one call does
it all. What the evidence means for a boundary with only some generated files
is the model's call.

Which files count:

  - A lockfile (`Cargo.lock`, `package-lock.json`, `yarn.lock`, `go.sum` and
    the rest of LOCKFILE_NAMES and LOCKFILE_SUFFIXES) and a non-source file
    (documentation, data and configuration, media, archives and binaries:
    NON_SOURCE_EXTENSIONS, NON_SOURCE_NAMES, every dotfile; build and tool
    configuration: every manifest skf-scan-manifests.py scans, setup.py,
    build.gradle and Package.swift included, the Gradle and Maven wrappers,
    Bazel files and `<tool>.config.<ext>` files such as vite.config.ts) is
    never a source file. It is never scanned for a header sentinel and
    never counted. Every other file is a source file, so a language these
    tables do not know still counts.
  - A source file is generated when its path below the boundary path holds
    a vendored or cache folder at any depth (node_modules/, vendor/,
    __pycache__/, .next/, .gradle/), or a build output folder (dist/,
    build/, target/) that is the first folder below the boundary or sits in
    a folder holding a manifest of the file list (a member package's own
    dist/); or else when one of its first 10 lines holds a generated-code
    sentinel (`@generated`, `// GENERATED CODE`, `# AUTOGENERATED`,
    `<!-- generated -->`, matched case-insensitively). So a package that
    itself lives in a folder named build/ is not generated, and neither is
    a source folder of that name further down (src/build/, the Java package
    folder com/acme/build/).

Rules, first match wins (kept in sync with
`src/skf-analyze-source/references/unit-detection-heuristics.md`):

  1. generated-code / auto-generated-tag: every source file of the boundary
     is generated (and it has at least one). generated-code when a
     directory segment marked any of them, auto-generated-tag when only
     header sentinels did.
  2. too-few-files: files_count < --min-files (default 3)
  3. too-low-loc:   loc_total < --min-loc (default 100)

`files_count` and `loc_total` count the source files that are not
generated; a line counts when its stripped form is not empty. A boundary
with some generated files is kept when it passes rules 2 and 3, and its
`generated_files` and `generated_ratio` are evidence the model weighs.
`passes_with_generated` says whether rules 2 and 3 pass with the generated
files counted too, so a boundary whose flagged files the model judges to be
its own code can be restored without counting them by hand.

Rules NOT enforced by this script (judged in identify-units section 2):
pure-configuration, test-only, already-skilled.

Manifest. Every record carries `manifest`, the boundary's own manifest: of
the manifests at the boundary root (the file names skf-scan-manifests.py
scans, its MANIFEST_ECOSYSTEMS), the first in path order that names a
package, else the first; null when there is none. It is
`{"path", "ecosystem", "name", "private"}`, `name` and `private` as that
script's identity readers report them, which skf-skill-inventory.py
derive-name takes to name the unit.

Signals. Every record carries `signals`, the detection signals of
unit-detection-heuristics.md that the file list shows, each the first file
that shows it (shallowest, then in path order) or null:

  own_manifest        the `manifest` path
  entry_point         an entry file (ENTRY_POINT_NAMES: index.ts, main.go,
                      lib.rs, __init__.py, ...) at most two folders below
                      the boundary root
  service_definition  a Dockerfile, Containerfile, compose file or
                      serverless.yml, at any depth (skf-scan-manifests.py's
                      is_service_definition, whose `services[]` lists them)
  readme              a README at the boundary root
  test_suite          a file in a test folder (test/, tests/, __tests__/,
                      spec/, specs/), a test file (*.test.*, *.spec.*,
                      *_test.*, test_*.py, *_spec.rb) or a test runner
                      configuration
  ci_reference        a CI configuration under --source-root (CI_FILE_GLOBS)
                      that names the boundary path; null for a boundary at
                      the root

and `large_directory`: true when the file list holds 50 or more files.

Boundary paths. Each `path` is normalized once, so `./packages/auth`,
`packages/auth/` and `packages/./auth` all read as `packages/auth` (and
`""` or `./` as `.`, the root); the record carries the normalized path. An
absolute path, or one that leaves the source root (`..`), is an error.

Listing. A boundary without `files` gets the files under
<source-root>/<path>: those git lists when the source root is in a git
work tree (tracked, and untracked but not ignored, so .gitignore holds and
an installed node_modules/ or a build's target/ stays out), else every file
of a walk that skips node_modules/ and __pycache__/. The walk also runs
when git lists no file there (a folder the outer work tree ignores, such
as an extracted tarball under an ignored vendor/). Hidden entries and
symbolic links are left out either way. Paths are relative to the source
root, forward-slash, sorted, each once. A boundary path that is no folder
under the source root is an error. With --tree-dir, each boundary's file
list (its listing, or the `files` it was given) is written there, one path
per line, as `boundary-<n>.txt` (n its 1-based place in the input), and
its record carries `tree_file`: the listing skf-detect-language.py
--tree-file reads for that unit, so no file list passes through the
caller. A file name that is not UTF-8 is written with `?` for each byte
that is not, so the listing stays one UTF-8 file.

Subcommands:
  filter --boundaries <json-file-or--for-stdin> [--source-root <path>]
                     [--tree-dir <folder>] [--min-files N] [--min-loc N]
                     [--project-path <path>]

      Read a boundaries JSON of the shape:
        [
          {"name": "<unit-name>",
           "path": "<rel-from-source-root>",
           "files": ["<rel-path>", ...]},   // optional: listed when absent
          ...
        ]
      and emit:
        {
          "project_path": "<path>",          // with --project-path only
          "kept":    [<record>, ...],
          "dropped": [<record> + {"reason": "<too-few-files|too-low-loc|"
                                             "generated-code|"
                                             "auto-generated-tag>",
                                  "context": {...}}, ...],
          "stats":   {"kept": N, "dropped": N, "mixed": N,
                      "by_reason": {"<reason>": N, ...}}
        }
      where every <record> is
        {"name": "...", "path": "...",
         "files_count": N, "loc_total": L, "non_source_count": K,
         "generated_files": [{"path": "...",
                              "reason": "generated-code|auto-generated-tag",
                              "match": "<segment or sentinel>"}, ...],
         "generated_ratio": R, "passes_with_generated": B,
         "manifest": {"path", "ecosystem", "name", "private"} | null,
         "signals": {"own_manifest": "<path>|null", ..., "large_directory": B},
         "tree_file": "<path>"}            // with --tree-dir only
      `generated_files` is sorted by path. `generated_ratio` is the share of
      the source files that are generated (0.0 with no source file), to
      three decimals. `context` holds the rule's own evidence: `threshold`
      for too-few-files and too-low-loc, `first_match` and
      `matched_segment` or `matched_sentinel` for the generated rules.
      `stats.mixed` counts the kept boundaries with generated files: the
      mixed cases the model judges.

  --source-root defaults to the current working directory. File paths in
  the `files[]` array are resolved against `<source-root>/<file-rel>` first
  and, when that does not exist, against
  `<source-root>/<boundary-path>/<file-rel>`. A file listed twice counts
  once. Missing files read as empty files; the boundary is still subject
  to the count and LoC thresholds. --project-path names the project path
  the boundaries were found under, which `units` reads from the envelope.

  units --filter <file> [--filter <file> ...] --names <file>
        --judgments <json-file-or--for-stdin> --out <file> [--add]

      Merge the saved `filter --project-path --tree-dir` envelopes (one
      --filter per project path), the saved `skf-skill-inventory.py
      derive-name --from` output and the model's judgments into the units
      file analyze-source's step-by-step chain carries from identify-units
      to map-and-detect, and print its tables. A judgment is
        {"project_path": "...", "path": "<record path>",
         "status": "new|briefed|deferred|dropped",
         "boundary_type": "...", "scope_type": "...",
         "confidence": "high|medium|low", "rationale": "...",
         "reason": "...",      // a dropped one
         "name": "...",        // optional: replaces the derived name
         "language": "..."}    // optional: replaces the detected language
      new, briefed and deferred keep a record (they need boundary_type,
      scope_type, confidence and rationale); dropped drops it (it needs
      reason and rationale). Every kept[] record needs one; a dropped[]
      record without one stays dropped with the script's reason and
      context, and one with a kept status is restored. A unit's name is
      the names[] entry whose `target` is its path (its project path for
      `.`, both read without a leading `./` or trailing `/`) and whose
      `manifest_name` is its manifest.name (null without a manifest); a
      judgment's `name` replaces it, and is required when that entry's
      name is null or not exactly one entry matches. Each unit's language
      is skf-detect-language.py's detect() over its tree_file (no
      workspace signal), unless its judgment names one (in lower case when
      that is a language scope_patterns() knows), and its `scope` the
      include and exclude scope_patterns() gives for that language
      (`unknown`'s for a language it does not know). The file is
        {"units": [{"name", "project_path", "path", "status",
                    "boundary_type", "scope_type", "confidence",
                    "rationale", "files_count", "loc_total", "manifest",
                    "generated_files", "generated_ratio", "signals",
                    "tree_file", "language",
                    "language_detection": {"language", "confidence",
                                           "detection_source",
                                           "detected_languages",
                                           "source_language"},
                    "scope": {"include", "exclude"}}, ...],
         "dropped": [{"project_path", "path", "name", "reason",
                      "context", "rationale"}, ...]}
      project paths in --filter order, each one's units in filter order
      (kept, then restored) and its drops in filter order (kept records
      judged dropped, then the script's drops). It is written through a
      temporary file and os.replace, with `?` for each file name byte that
      is not UTF-8. Without --add it holds this call's
      project paths only; with --add the units and drops the file already
      holds for other project paths stay first. Stdout gets three
      markdown tables of this call's project paths, as UTF-8: Identified
      units, Language and scope, and Disqualified.

CLI examples:
  uv run skf-disqualify-candidates.py filter --boundaries boundaries.json
  cat boundaries.json | uv run skf-disqualify-candidates.py filter \\
      --boundaries - --source-root /path/to/project --tree-dir /tmp/trees \\
      --project-path https://github.com/acme/mono > filter-1.json
  uv run skf-disqualify-candidates.py units --filter filter-1.json \\
      --names unit-names.json --judgments unit-judgments.json \\
      --out analyze-source-units-acme.json

Exit codes:
  0  operation succeeded (including: empty input, which gives empty kept
     and dropped lists)
  1  user error (bad JSON, missing required keys, malformed entry, a
     boundary path that is absolute or leaves the source root, a boundary
     path to list that is no folder, a --tree-dir that cannot be
     written), or no skf-scan-manifests.py beside this script that loads
     (it needs Python 3.11 for tomllib, hence this script's floor). For
     `units`: a kept record without a judgment, a judgment that names no
     record, a record judged twice, a judgment missing a field or with an
     unknown status or confidence, a filter envelope without
     `project_path` or a `kept` or `dropped` list, a record without
     `tree_file`, a boundary one filter lists twice, two --filter files of
     one project path, a names file holding a derive-name error or no
     `names` list, an --add file without `units` and `dropped` lists, a
     unit without a name or two units sharing one, a tree file that cannot be read, or
     no skf-detect-language.py beside this script that loads; stderr
     names each, and nothing is written
"""

