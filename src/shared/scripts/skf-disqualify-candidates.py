def _read_boundaries_source(source: str) -> object:
    """Read boundaries JSON from a file path or stdin (if source == '-')."""
    if source == "-":
        try:
            text = sys.stdin.read()
        except OSError as exc:
            raise ValueError(
                f"failed to read boundaries JSON from stdin: {exc}"
            ) from exc
    else:
        path = Path(source)
        if not path.is_file():
            raise ValueError(f"boundaries file not found: {path}")
        try:
            text = path.read_text(encoding="utf-8")
        except OSError as exc:
            raise ValueError(
                f"failed to read boundaries file {path}: {exc}"
            ) from exc
    try:
        return json.loads(text)
    except json.JSONDecodeError as exc:
        raise ValueError(f"malformed JSON in boundaries input: {exc}") from exc


def _cmd_filter(args: argparse.Namespace) -> int:
    try:
        raw = _read_boundaries_source(args.boundaries)
        boundaries = validate_boundaries(raw)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    source_root = Path(args.source_root or ".").resolve()
    if not source_root.is_dir():
        print(
            f"error: source-root not a directory: {source_root}", file=sys.stderr
        )
        return 1

    if args.min_files < 0:
        print(
            f"error: --min-files must be >= 0; got {args.min_files}",
            file=sys.stderr,
        )
        return 1
    if args.min_loc < 0:
        print(
            f"error: --min-loc must be >= 0; got {args.min_loc}",
            file=sys.stderr,
        )
        return 1

    try:
        manifest_filenames()
    except (ImportError, OSError, SyntaxError, AttributeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    tree_dir = Path(args.tree_dir).resolve() if args.tree_dir else None
    try:
        result = filter_boundaries(
            boundaries,
            source_root=source_root,
            min_files=args.min_files,
            min_loc=args.min_loc,
            tree_dir=tree_dir,
        )
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    except OSError as exc:
        print(f"error: cannot write a tree file under {tree_dir}: {exc}", file=sys.stderr)
        return 1
    if args.project_path is not None:
        result = {"project_path": args.project_path, **result}
    json.dump(result, sys.stdout, indent=2)
    sys.stdout.write("\n")
    return 0


def _read_json_input(source: str, what: str, *, stdin: bool = False) -> object:
    """A JSON input from a file, or from stdin for `-` when `stdin` is true.
    Raises ValueError naming it."""
    if stdin and source == "-":
        buffer = getattr(sys.stdin, "buffer", None)
        try:
            text = buffer.read().decode("utf-8-sig") if buffer is not None else sys.stdin.read()
        except (OSError, UnicodeDecodeError) as exc:
            raise ValueError(f"cannot read {what} from stdin: {exc}") from exc
    else:
        try:
            text = Path(source).read_text(encoding="utf-8-sig")
        except (OSError, UnicodeDecodeError) as exc:
            raise ValueError(f"cannot read {what} {source}: {exc}") from exc
    try:
        return json.loads(text)
    except json.JSONDecodeError as exc:
        raise ValueError(f"{what} {source} is not valid JSON: {exc}") from exc


def _cmd_units(args: argparse.Namespace) -> int:
    out = Path(args.out)
    try:
        filters = [(source, _read_json_input(source, "--filter")) for source in args.filter]
        names = _read_json_input(args.names, "--names")
        judgments = _read_json_input(args.judgments, "--judgments", stdin=True)
        existing = _read_json_input(str(out), "--out") if args.add and out.exists() else None
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    try:
        detector = detect_language_module()
    except (ImportError, OSError, SyntaxError, AttributeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    try:
        data, units, drops = merge_units(filters, names, judgments, existing=existing, detector=detector)
    except UnitsError as exc:
        for problem in exc.problems:
            print(f"error: {problem}", file=sys.stderr)
        print(f"error: nothing was written to {out}", file=sys.stderr)
        return 1
    try:
        write_units_file(out, data)
    except OSError as exc:
        print(f"error: cannot write {out}: {exc}", file=sys.stderr)
        return 1
    _write_utf8(render_units_tables(units, drops))
    return 0


