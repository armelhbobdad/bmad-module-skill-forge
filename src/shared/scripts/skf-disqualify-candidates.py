def _basename(file_path: str) -> str:
    return file_path.replace("\\", "/").rsplit("/", 1)[-1]


def is_lockfile(file_path: str) -> bool:
    """True for a dependency lockfile (by file name)."""
    name = _basename(file_path).lower()
    return name in LOCKFILE_NAMES or name.endswith(LOCKFILE_SUFFIXES)


def is_non_source(file_path: str) -> bool:
    """True for documentation, data, configuration, media and binary files,
    and for build and tool configuration (every manifest included).

    Lockfiles are non-source too. A file with an extension the tables do
    not list is a source file.
    """
    name = _basename(file_path).lower()
    if not name or name.startswith("."):
        return True
    scan_manifests_module()
    if (
        is_lockfile(name)
        or name in NON_SOURCE_NAMES
        or name in _MANIFEST_FILENAMES_LC
        or name.startswith(NON_SOURCE_PREFIXES)
        or name.endswith(".dockerfile")
        or any(infix in name for infix in NON_SOURCE_INFIXES)
    ):
        return True
    ext = posixpath.splitext(name)[1]
    return ext in NON_SOURCE_EXTENSIONS


