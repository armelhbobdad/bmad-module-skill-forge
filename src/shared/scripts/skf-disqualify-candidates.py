def _read_boundaries_source(source: str) -> object:
    """Read boundaries JSON from a file path or stdin (if source == '-')."""
    if source == "-":
        try:
            text = sys.stdin.read()
        except OSError as exc:
            raise ValueError(
                f"failed to read boundaries JSON from stdin: {exc}"
            ) from exc
    else:
        path = Path(source)
        if not path.is_file():
            raise ValueError(f"boundaries file not found: {path}")
        try:
            text = path.read_text(encoding="utf-8")
        except OSError as exc:
            raise ValueError(
                f"failed to read boundaries file {path}: {exc}"
            ) from exc
    try:
        return json.loads(text)
    except json.JSONDecodeError as exc:
        raise ValueError(f"malformed JSON in boundaries input: {exc}") from exc


def _cmd_filter(args: argparse.Namespace) -> int:
    try:
        raw = _read_boundaries_source(args.boundaries)
        boundaries = validate_boundaries(raw)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    source_root = Path(args.source_root or ".").resolve()
    if not source_root.is_dir():
        print(
            f"error: source-root not a directory: {source_root}", file=sys.stderr
        )
        return 1

    if args.min_files < 0:
        print(
            f"error: --min-files must be >= 0; got {args.min_files}",
            file=sys.stderr,
        )
        return 1
    if args.min_loc < 0:
        print(
            f"error: --min-loc must be >= 0; got {args.min_loc}",
            file=sys.stderr,
        )
        return 1

    try:
        manifest_filenames()
    except (ImportError, OSError, SyntaxError, AttributeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    result = filter_boundaries(
        boundaries,
        source_root=source_root,
        min_files=args.min_files,
        min_loc=args.min_loc,
    )
    json.dump(result, sys.stdout, indent=2)
    sys.stdout.write("\n")
    return 0


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="skf-disqualify-candidates",
        description=(
            "Filter detected boundaries against the unit-detection "
            "disqualification list (generated-code and auto-generated-tag "
            "when every source file is generated, too-few-files, "
            "too-low-loc), with each boundary's generated files and "
            "detection signals as evidence."
        ),
    )
    sub = parser.add_subparsers(dest="cmd", required=True)

    p_filter = sub.add_parser(
        "filter",
        help="emit kept/dropped/stats partition as JSON",
    )
    p_filter.add_argument(
        "--boundaries",
        required=True,
        help=(
            "path to boundaries JSON, or '-' to read from stdin. "
            "Shape: [{\"name\": \"<unit>\", \"path\": \"<rel>\", "
            "\"files\": [\"<rel>\", ...]}, ...]"
        ),
    )
    p_filter.add_argument(
        "--source-root",
        default=None,
        help=(
            "project root for resolving file paths in `files[]` and for the "
            "CI configurations ci_reference reads (default: current working "
            "directory). Each file is resolved as <source-root>/<file-rel> "
            "first, falling back to <source-root>/<boundary-path>/<file-rel>."
        ),
    )
    p_filter.add_argument(
        "--min-files",
        type=int,
        default=MIN_FILES,
        help=(
            f"minimum source files (not generated) for too-few-files "
            f"(default {MIN_FILES}; matches unit-detection-heuristics.md)"
        ),
    )
    p_filter.add_argument(
        "--min-loc",
        type=int,
        default=MIN_LOC,
        help=(
            f"minimum non-blank LoC of those files for too-low-loc "
            f"(default {MIN_LOC}; matches unit-detection-heuristics.md)"
        ),
    )
    p_filter.set_defaults(func=_cmd_filter)

    return parser


def main(argv: list[str] | None = None) -> int:
    parser = _build_parser()
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
