"""SKF Disqualify Candidates: size, generated-code and signal evidence per boundary.

`identify-units.md` section 2 hands this helper every detected boundary with
its file list. What it checks has one right answer per file list (file and
line counts, generated or vendored directory segments, generated-code header
sentinels, which signal files exist, what the boundary's own manifest names),
and prior runs showed models miscount files, miss generated paths inside
nested `node_modules/` and forget to scan for `@generated`, so one call does
it all. What the evidence means for a boundary with only some generated files
is the model's call.

Which files count:

  - A lockfile (`Cargo.lock`, `package-lock.json`, `yarn.lock`, `go.sum` and
    the rest of LOCKFILE_NAMES and LOCKFILE_SUFFIXES) and a non-source file
    (documentation, data and configuration, media, archives and binaries:
    NON_SOURCE_EXTENSIONS, NON_SOURCE_NAMES, every dotfile; build and tool
    configuration: every manifest skf-scan-manifests.py scans, setup.py,
    build.gradle and Package.swift included, the Gradle and Maven wrappers,
    Bazel files and `<tool>.config.<ext>` files such as vite.config.ts) is
    never a source file. It is never scanned for a header sentinel and
    never counted. Every other file is a source file, so a language these
    tables do not know still counts.
  - A source file is generated when its path below the boundary path holds
    a vendored or cache folder at any depth (node_modules/, vendor/,
    __pycache__/, .next/, .gradle/), or a build output folder (dist/,
    build/, target/) that is the first folder below the boundary or sits in
    a folder holding a manifest of the file list (a member package's own
    dist/); or else when one of its first 10 lines holds a generated-code
    sentinel (`@generated`, `// GENERATED CODE`, `# AUTOGENERATED`,
    `<!-- generated -->`, matched case-insensitively). So a package that
    itself lives in a folder named build/ is not generated, and neither is
    a source folder of that name further down (src/build/, the Java package
    folder com/acme/build/).

Rules, first match wins (kept in sync with
`src/skf-analyze-source/references/unit-detection-heuristics.md`):

  1. generated-code / auto-generated-tag: every source file of the boundary
     is generated (and it has at least one). generated-code when a
     directory segment marked any of them, auto-generated-tag when only
     header sentinels did.
  2. too-few-files: files_count < --min-files (default 3)
  3. too-low-loc:   loc_total < --min-loc (default 100)

`files_count` and `loc_total` count the source files that are not
generated; a line counts when its stripped form is not empty. A boundary
with some generated files is kept when it passes rules 2 and 3, and its
`generated_files` and `generated_ratio` are evidence the model weighs.
`passes_with_generated` says whether rules 2 and 3 pass with the generated
files counted too, so a boundary whose flagged files the model judges to be
its own code can be restored without counting them by hand.

Rules NOT enforced by this script (judged in identify-units section 2):
pure-configuration, test-only, already-skilled.

Manifest. Every record carries `manifest`, the boundary's own manifest: of
the manifests at the boundary root (the file names skf-scan-manifests.py
scans, its MANIFEST_ECOSYSTEMS), the first in path order that names a
package, else the first; null when there is none. It is
`{"path", "ecosystem", "name", "private"}`, `name` and `private` as that
script's identity readers report them, which skf-skill-inventory.py
derive-name takes to name the unit.

Signals. Every record carries `signals`, the detection signals of
unit-detection-heuristics.md that the file list shows, each the first file
that shows it (shallowest, then in path order) or null:

  own_manifest        the `manifest` path
  entry_point         an entry file (ENTRY_POINT_NAMES: index.ts, main.go,
                      lib.rs, __init__.py, ...) at most two folders below
                      the boundary root
  service_definition  a Dockerfile, Containerfile, compose file or
                      serverless.yml, at any depth
  readme              a README at the boundary root
  test_suite          a file in a test folder (test/, tests/, __tests__/,
                      spec/, specs/), a test file (*.test.*, *.spec.*,
                      *_test.*, test_*.py, *_spec.rb) or a test runner
                      configuration
  ci_reference        a CI configuration under --source-root (CI_FILE_GLOBS)
                      that names the boundary path; null for a boundary at
                      the root

and `large_directory`: true when the file list holds 50 or more files.

Subcommand:
  filter --boundaries <json-file-or--for-stdin> [--source-root <path>]
                     [--min-files N] [--min-loc N]

      Read a boundaries JSON of the shape:
        [
          {"name": "<unit-name>",
           "path": "<rel-from-source-root>",
           "files": ["<rel-path>", ...]},
          ...
        ]
      and emit:
        {
          "kept":    [<record>, ...],
          "dropped": [<record> + {"reason": "<too-few-files|too-low-loc|"
                                             "generated-code|"
                                             "auto-generated-tag>",
                                  "context": {...}}, ...],
          "stats":   {"kept": N, "dropped": N, "mixed": N,
                      "by_reason": {"<reason>": N, ...}}
        }
      where every <record> is
        {"name": "...", "path": "...",
         "files_count": N, "loc_total": L, "non_source_count": K,
         "generated_files": [{"path": "...",
                              "reason": "generated-code|auto-generated-tag",
                              "match": "<segment or sentinel>"}, ...],
         "generated_ratio": R, "passes_with_generated": B,
         "manifest": {"path", "ecosystem", "name", "private"} | null,
         "signals": {"own_manifest": "<path>|null", ..., "large_directory": B}}
      `generated_files` is sorted by path. `generated_ratio` is the share of
      the source files that are generated (0.0 with no source file), to
      three decimals. `context` holds the rule's own evidence: `threshold`
      for too-few-files and too-low-loc, `first_match` and
      `matched_segment` or `matched_sentinel` for the generated rules.
      `stats.mixed` counts the kept boundaries with generated files: the
      mixed cases the model judges.

  --source-root defaults to the current working directory. File paths in
  the `files[]` array are resolved against `<source-root>/<file-rel>` first
  and, when that does not exist, against
  `<source-root>/<boundary-path>/<file-rel>`. A file listed twice counts
  once. Missing files read as empty files; the boundary is still subject
  to the count and LoC thresholds.

CLI examples:
  uv run skf-disqualify-candidates.py filter --boundaries boundaries.json
  cat boundaries.json | uv run skf-disqualify-candidates.py filter \\
      --boundaries - --source-root /path/to/project

Exit codes:
  0  operation succeeded (including: empty input, which gives empty kept
     and dropped lists)
  1  user error (bad JSON, missing required keys, malformed entry), or no
     skf-scan-manifests.py beside this script that loads (it needs Python
     3.11 for tomllib, hence this script's floor)
"""

