def load_ci_files(source_root: Path) -> list[tuple[str, str]]:
    """Read the CI configurations under `source_root`: (rel path, text) pairs,
    sorted by path. Unreadable files are left out.
    """
    found: dict[str, str] = {}
    for pattern in CI_FILE_GLOBS:
        for path in source_root.glob(pattern):
            if not path.is_file():
                continue
            try:
                text = path.read_bytes().decode("utf-8", errors="replace")
            except OSError:
                continue
            found[path.relative_to(source_root).as_posix()] = text
    return sorted(found.items())


def _names_path(text: str, boundary_path: str) -> bool:
    """True when `text` names `boundary_path` as a whole path: not as part
    of a longer name (`packages/auth` is not named by `packages/auth-ui`).
    """
    pattern = r"(?<![\w-])" + re.escape(boundary_path) + r"(?![\w.-])"
    return re.search(pattern, text) is not None


def _is_test_file(rel: str) -> bool:
    parts = rel.split("/")
    if any(part.lower() in TEST_FOLDERS for part in parts[:-1]):
        return True
    name = parts[-1].lower()
    if name in TEST_CONFIG_NAMES or name.startswith(TEST_CONFIG_PREFIXES):
        return True
    return TEST_FILE_RE.search(name) is not None


def collect_signals(
    files: list[str],
    boundary_path: str,
    ci_files: list[tuple[str, str]],
) -> dict:
    """The presence flags of one boundary; see the module docstring."""
    signals: dict = {key: None for key in SIGNAL_KEYS}
    manifests = manifest_filenames()
    entry_depth: int | None = None
    for f in sorted(files):
        rel = below_boundary(f, boundary_path)
        depth = rel.count("/")
        name = _basename(rel)
        lname = name.lower()
        if depth == 0 and signals["own_manifest"] is None and name in manifests:
            signals["own_manifest"] = f
        if depth == 0 and signals["readme"] is None and lname.startswith("readme"):
            signals["readme"] = f
        if (
            lname in ENTRY_POINT_NAMES
            and depth <= ENTRY_POINT_MAX_DEPTH
            and (entry_depth is None or depth < entry_depth)
        ):
            signals["entry_point"] = f
            entry_depth = depth
        if (
            signals["service_definition"] is None
            and scan_manifests_module().is_service_definition(name)
        ):
            signals["service_definition"] = f
        if signals["test_suite"] is None and _is_test_file(rel):
            signals["test_suite"] = f
    root = boundary_path.strip("/")
    if root not in ("", "."):
        for ci_path, text in ci_files:
            if _names_path(text, root):
                signals["ci_reference"] = ci_path
                break
    signals["large_directory"] = len(files) >= LARGE_DIRECTORY_FILES
    return signals


