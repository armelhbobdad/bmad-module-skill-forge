def _resolve_file(source_root: Path, boundary_path: str, file_rel: str) -> Path:
    """Resolve a boundary's `files[]` entry to an absolute path.

    Tries in order:
      1. <source_root>/<file_rel>            (file_rel already source-root-relative)
      2. <source_root>/<boundary_path>/<file_rel>  (file_rel boundary-relative)

    The first existing path wins; otherwise returns the source-root option
    so downstream code can decide what "missing" means.
    """
    candidate_a = source_root / file_rel
    if candidate_a.is_file():
        return candidate_a
    candidate_b = source_root / boundary_path / file_rel
    if candidate_b.is_file():
        return candidate_b
    # neither exists: return the source-root form for missing-file accounting
    return candidate_a


def classify_file(
    file_rel: str,
    boundary_path: str,
    source_root: Path,
    manifest_dirs: frozenset[str] | set[str] = frozenset(),
) -> dict | None:
    """The generated-file entry for one source file, or None when the file
    is not generated. Call it for source files only (see is_non_source);
    `manifest_dirs` is find_generated_segment's.
    """
    rel = below_boundary(file_rel, boundary_path)
    seg = find_generated_segment(rel, manifest_dirs)
    if seg:
        return {"path": file_rel, "reason": REASON_GENERATED_CODE, "match": seg}
    sentinel = has_auto_generated_marker(
        _resolve_file(source_root, boundary_path, file_rel)
    )
    if sentinel:
        return {
            "path": file_rel, "reason": REASON_AUTO_GENERATED_TAG, "match": sentinel,
        }
    return None


def evaluate_boundary(
    boundary: dict,
    *,
    source_root: Path,
    min_files: int = MIN_FILES,
    min_loc: int = MIN_LOC,
    ci_files: list[tuple[str, str]] | None = None,
) -> dict:
    """Evaluate a single boundary against all disqualification rules.

    Returns {"kind": "kept" | "dropped", "record": {...}}; the record shape
    is the module docstring's <record>, and a dropped one adds `reason` and
    `context`.

    Check order:
      1. generated-code / auto-generated-tag (every source file generated)
      2. too-few-files      (files_count < min_files)
      3. too-low-loc        (loc_total < min_loc)
    """
    name = boundary["name"]
    path = boundary["path"]
    files = list(dict.fromkeys(boundary["files"]))  # a file listed twice counts once
    if ci_files is None:
        ci_files = load_ci_files(source_root)

    manifests = manifest_filenames()
    manifest_dirs = {
        posixpath.dirname(below_boundary(f, path))
        for f in files
        if _basename(f) in manifests
    }
    sources = [f for f in files if not is_non_source(f)]
    generated: list[dict] = []
    plain: list[str] = []
    for f in sources:
        entry = classify_file(f, path, source_root, manifest_dirs)
        if entry:
            generated.append(entry)
        else:
            plain.append(f)
    generated.sort(key=lambda g: g["path"])

    loc_total = 0
    for f in plain:
        loc_total += count_nonblank_lines(_resolve_file(source_root, path, f))

    # Would rules 2 and 3 pass with the generated files counted too? Their
    # lines are read only when that decides it.
    passes = len(plain) >= min_files and loc_total >= min_loc
    if not passes and len(sources) >= min_files:
        loc = loc_total
        for g in generated:
            if loc >= min_loc:
                break
            loc += count_nonblank_lines(_resolve_file(source_root, path, g["path"]))
        passes = loc >= min_loc

    manifest = own_manifest(files, path, source_root)
    signals = collect_signals(files, path, ci_files)
    signals["own_manifest"] = manifest["path"] if manifest else None
    record = {
        "name": name,
        "path": path,
        "files_count": len(plain),
        "loc_total": loc_total,
        "non_source_count": len(files) - len(sources),
        "generated_files": generated,
        "generated_ratio": (
            round(len(generated) / len(sources), 3) if sources else 0.0
        ),
        "passes_with_generated": passes,
        "manifest": manifest,
        "signals": signals,
    }

    # 1. every source file generated
    if sources and not plain:
        by_path = [g for g in generated if g["reason"] == REASON_GENERATED_CODE]
        if by_path:
            reason, first = REASON_GENERATED_CODE, by_path[0]
            key = "matched_segment"
        else:
            reason, first = REASON_AUTO_GENERATED_TAG, generated[0]
            key = "matched_sentinel"
        context = {"first_match": first["path"], key: first["match"]}
        return {
            "kind": "dropped",
            "record": {**record, "reason": reason, "context": context},
        }

    # 2. too-few-files
    if len(plain) < min_files:
        return {
            "kind": "dropped",
            "record": {**record, "reason": REASON_TOO_FEW_FILES,
                       "context": {"threshold": min_files}},
        }

    # 3. too-low-loc
    if loc_total < min_loc:
        return {
            "kind": "dropped",
            "record": {**record, "reason": REASON_TOO_LOW_LOC,
                       "context": {"threshold": min_loc}},
        }

    return {"kind": "kept", "record": record}


