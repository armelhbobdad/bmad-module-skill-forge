    parser = argparse.ArgumentParser(
        prog="skf-disqualify-candidates",
        description=(
            "Filter detected boundaries against the unit-detection "
            "disqualification list (generated-code and auto-generated-tag "
            "when every source file is generated, too-few-files, "
            "too-low-loc), with each boundary's generated files and "
            "detection signals as evidence, and merge the saved results "
            "with their names and judgments into analyze-source's units file."
        ),
    )
    sub = parser.add_subparsers(dest="cmd", required=True)

    p_filter = sub.add_parser(
        "filter",
        help="emit kept/dropped/stats partition as JSON",
    )
    p_filter.add_argument(
        "--boundaries",
        required=True,
        help=(
            "path to boundaries JSON, or '-' to read from stdin. "
            "Shape: [{\"name\": \"<unit>\", \"path\": \"<rel>\", "
            "\"files\": [\"<rel>\", ...]}, ...]; without files the "
            "helper lists the files under the path"
        ),
    )
    p_filter.add_argument(
        "--source-root",
        default=None,
        help=(
            "project root for listing a boundary's files, resolving file "
            "paths in `files[]` and the CI configurations ci_reference reads "
            "(default: current working directory). Each file is resolved as "
            "<source-root>/<file-rel> first, falling back to "
            "<source-root>/<boundary-path>/<file-rel>."
        ),
    )
    p_filter.add_argument(
        "--tree-dir",
        default=None,
        help=(
            "folder to write each boundary's file list to, one path per line "
            "(boundary-<n>.txt, n its place in the input); each record names "
            "its file in tree_file"
        ),
    )
    p_filter.add_argument(
        "--min-files",
        type=int,
        default=MIN_FILES,
        help=(
            f"minimum source files (not generated) for too-few-files "
            f"(default {MIN_FILES}; matches unit-detection-heuristics.md)"
        ),
    )
    p_filter.add_argument(
        "--min-loc",
        type=int,
        default=MIN_LOC,
        help=(
            f"minimum non-blank LoC of those files for too-low-loc "
            f"(default {MIN_LOC}; matches unit-detection-heuristics.md)"
        ),
    )
    p_filter.add_argument(
        "--project-path",
        default=None,
        help=(
            "the project path the boundaries were found under, written to "
            "the envelope's project_path for `units`"
        ),
    )
