def scan_manifests_module():
    """skf-scan-manifests.py, loaded once from beside this script.
    Raises ImportError when it cannot be loaded.
    """
    global _SCAN_MODULE, _MANIFEST_FILENAMES, _MANIFEST_FILENAMES_LC
    if _SCAN_MODULE is None:
        spec = importlib.util.spec_from_file_location(
            "skf_scan_manifests", SCAN_MANIFESTS
        )
        if spec is None or spec.loader is None or not SCAN_MANIFESTS.is_file():
            raise ImportError(f"cannot load {SCAN_MANIFESTS}")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        if not hasattr(module, "IDENTITY_READERS"):
            raise ImportError(f"{SCAN_MANIFESTS} has no IDENTITY_READERS")
        _MANIFEST_FILENAMES = frozenset(module.MANIFEST_ECOSYSTEMS)
        _MANIFEST_FILENAMES_LC = frozenset(n.lower() for n in _MANIFEST_FILENAMES)
        _SCAN_MODULE = module
    return _SCAN_MODULE


def manifest_filenames() -> frozenset[str]:
    """The manifest file names skf-scan-manifests.py scans (the keys of its
    MANIFEST_ECOSYSTEMS). Raises ImportError when it cannot be loaded.
    """
    scan_manifests_module()
    return _MANIFEST_FILENAMES


def _basename(file_path: str) -> str:
    return file_path.replace("\\", "/").rsplit("/", 1)[-1]


def is_lockfile(file_path: str) -> bool:
    """True for a dependency lockfile (by file name)."""
    name = _basename(file_path).lower()
    return name in LOCKFILE_NAMES or name.endswith(LOCKFILE_SUFFIXES)


def is_non_source(file_path: str) -> bool:
    """True for documentation, data, configuration, media and binary files,
    and for build and tool configuration (every manifest included).

    Lockfiles are non-source too. A file with an extension the tables do
    not list is a source file.
    """
    name = _basename(file_path).lower()
    if not name or name.startswith("."):
        return True
    scan_manifests_module()
    if (
        is_lockfile(name)
        or name in NON_SOURCE_NAMES
        or name in _MANIFEST_FILENAMES_LC
        or name.startswith(NON_SOURCE_PREFIXES)
        or name.endswith(".dockerfile")
        or any(infix in name for infix in NON_SOURCE_INFIXES)
    ):
        return True
    ext = posixpath.splitext(name)[1]
    return ext in NON_SOURCE_EXTENSIONS


