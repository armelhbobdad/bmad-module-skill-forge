def find_generated_segment(
    file_path: str, manifest_dirs: frozenset[str] | set[str] = frozenset()
) -> str | None:
    """The generated-folder segment that marks `file_path`, a path below the
    boundary, or None.

    A vendored or cache folder counts at any depth (`node_modules/foo.js`
    and `pkg/node_modules/foo.js` both hit). A build output folder counts
    as the first folder, or inside a folder of `manifest_dirs`: the folders
    below the boundary that hold a manifest ("" for the boundary root). The
    leftmost folder that counts is returned.
    """
    parts = [p for p in file_path.replace("\\", "/").split("/")[:-1] if p != "."]
    for depth, part in enumerate(parts):
        seg = part + "/"
        if seg in VENDORED_PATH_SEGMENTS:
            return seg
        if seg in OUTPUT_PATH_SEGMENTS and (
            depth == 0 or "/".join(parts[:depth]) in manifest_dirs
        ):
            return seg
    return None


def below_boundary(file_path: str, boundary_path: str) -> str:
    """The part of `file_path` below the boundary folder.

    A path that does not start with the boundary path (a boundary-relative
    entry, or a boundary at the root) is returned whole.
    """
    root = boundary_path.strip("/")
    if root in ("", "."):
        return file_path
    prefix = root + "/"
    return file_path[len(prefix):] if file_path.startswith(prefix) else file_path


# --------------------------------------------------------------------------
# Header-sentinel scan (auto-generated-tag)
# --------------------------------------------------------------------------


_AUTO_GEN_SENTINELS_LC = tuple(s.lower() for s in AUTO_GEN_SENTINELS)


def has_auto_generated_marker(file_abs: Path) -> str | None:
    """Scan the first AUTO_GEN_HEADER_LINES lines of `file_abs` for any of
    the AUTO_GEN_SENTINELS (case-insensitive substring match).

    Returns the matched sentinel (lowercased) on first hit, or None.
    Unreadable / non-UTF-8 files return None: header-sentinel detection
    is opportunistic, and binary blobs will simply not match.
    """
    try:
        with file_abs.open("r", encoding="utf-8", errors="replace") as fh:
            for i, raw_line in enumerate(fh):
                if i >= AUTO_GEN_HEADER_LINES:
                    break
                lc = raw_line.lower()
                for sentinel in _AUTO_GEN_SENTINELS_LC:
                    if sentinel in lc:
                        return sentinel
    except OSError:
        return None
    return None


# --------------------------------------------------------------------------
# LoC counting
# --------------------------------------------------------------------------


def count_nonblank_lines(file_abs: Path) -> int:
    """Count lines whose stripped form is non-empty. Whitespace-only lines
    count as blank. Returns 0 for unreadable files.
    """
    try:
        with file_abs.open("r", encoding="utf-8", errors="replace") as fh:
            n = 0
            for line in fh:
                if line.strip():
                    n += 1
            return n
    except OSError:
        return 0


